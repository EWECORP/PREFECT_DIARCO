			K_MARGEN_SEGURO, M_ABAST_LOGISTICO, 
			C_HORA_APERTURA, C_HORA_CIERRE,C_LATITUD,C_LONGITUD,M_EXCLUIDA, M_TIPO_SUCURSAL,
			FUENTE_ORIGEN, FECHA_EXTRACCION, CDC_LSN, ESTADO_SINCRONIZACION
        )
        SELECT
            S.C_SUCU_EMPR,
            S.N_SUCURSAL,
            S.N_SUCURSAL_ABREV,
            S.N_SUCURSAL_ABREV2,
            S.N_CALLE,
            S.N_LOCALIDAD,
            S.C_POSTAL_INM,
            S.C_TELEFONO,
            S.D_POSIC_IVA,
            S.U_CUIT,
            S.U_IB,
            S.D_CAJA_JUBILAC,
            S.U_JUBILAC,
            S.M_BAJA,
            S.C_PROVINCIA_SUCU,
            S.F_INICIO_ACTIV_SUCU,
            S.C_ORDEN_PANTALLA,
            S.M_SUCU_VIRTUAL,
            S.M_HABILITADA_COMPRA,
            S.C_BACK_COLOR_SUCU,
            S.C_FORE_COLOR_SUCU,
            S.C_ZONA,
            S.N_DIRECTORIO_MAILHORA,
            S.N_DIRECTORIO_DATOS_SUC,
            S.C_EAN,
            S.U_EMAIL_SUCU,
            S.F_MODIF,
            S.N_DIRECTORIO_CIERRE_LOCAL_SUCURSAL,
            S.N_DIRECTORIO_RECEPCION_SUCURSAL,
            S.M_SUCURSAL_IMPLEMENTADA,
            S.N_SUCURSAL_ABREV3,
            S.N_GERENTE_SUC,
            S.N_GERENTE_TELEFONO_FLOTA,
            S.M_SUCURSAL_FISCALIZADA,
            S.F_FISCALIZACION,
