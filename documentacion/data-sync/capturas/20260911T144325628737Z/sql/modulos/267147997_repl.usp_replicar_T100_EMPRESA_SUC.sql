    DECLARE @inicio DATETIME = GETDATE();
    DECLARE @mensaje NVARCHAR(4000);
    DECLARE @total INT = 0;

    BEGIN TRY
        TRUNCATE TABLE repl.T100_EMPRESA_SUC_STG;

        INSERT INTO repl.T100_EMPRESA_SUC_STG (
            C_SUCU_EMPR, N_SUCURSAL, N_SUCURSAL_ABREV, N_SUCURSAL_ABREV2, N_CALLE, N_LOCALIDAD, C_POSTAL_INM, C_TELEFONO, D_POSIC_IVA, U_CUIT, U_IB, D_CAJA_JUBILAC, U_JUBILAC, M_BAJA, 
			C_PROVINCIA_SUCU, F_INICIO_ACTIV_SUCU, C_ORDEN_PANTALLA, M_SUCU_VIRTUAL, M_HABILITADA_COMPRA, C_BACK_COLOR_SUCU, C_FORE_COLOR_SUCU, C_ZONA, N_DIRECTORIO_MAILHORA, N_DIRECTORIO_DATOS_SUC, 
			C_EAN, U_EMAIL_SUCU, F_MODIF, N_DIRECTORIO_CIERRE_LOCAL_SUCURSAL, N_DIRECTORIO_RECEPCION_SUCURSAL, M_SUCURSAL_IMPLEMENTADA, N_SUCURSAL_ABREV3, N_GERENTE_SUC, N_GERENTE_TELEFONO_FLOTA, 
